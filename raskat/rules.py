# все уже сыгранные дни станут другими, а сервер и мини-апп перестанут сходиться со сборкой (раздел 3)
SALT = "raskat-2026/27"


def salt() -> str:
    """Соль сезона: переменная окружения `RASKAT_SALT`, иначе константа выше.

    С открытой солью завтрашний расклад решается заранее, и очки за время превращаются в очки за
    «решил вечером». Секрет в задании Pages и на сервере это закрывает; пока его нет, живём с
    солью из репозитория — это игра болельщиков, а не киберспорт (раздел 3)."""
    return os.environ.get("RASKAT_SALT") or SALT


