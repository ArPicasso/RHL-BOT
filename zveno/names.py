def gate_name(club: str, name: str) -> str:
    """«Ворота «Рязани-ВДВ»»; для составных названий без бесспорной формы — «Ворота клуба «…»»."""
    if club in GATE_GENITIVE:
        return f"Ворота «{GATE_GENITIVE[club]}»"
    return f"Ворота клуба «{name}»"


def is_valid(name) -> bool:
    """Название из конструктора: [прилагательное, существительное] из списков."""
